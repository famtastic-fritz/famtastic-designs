import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync, readFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync, spawnSync } from 'node:child_process';
import { addCreatorCredit, approvedLogo, creatorCreditHtml, LOGO_SHA256, sha256 } from './creator-credit.mjs';
test('exact owner bytes and passive, accessible credit', () => {
  assert.equal(sha256(approvedLogo()), LOGO_SHA256);
  const html = creatorCreditHtml();
  assert.match(html, /aria-label="Created by FAMtastic Designs"/);
  assert.match(html, /min-height:44px/);
  assert.match(html, /width:180px/);
  assert.match(html, /utm_source=famtastic-designs&amp;utm_medium=creator_credit&amp;utm_campaign=created_by_famtastic/);
  assert.doesNotMatch(html, /<script|cookie|filter:(?!none)/i);
});
test('preserves footer and authored HTML, appends once', () => {
  const source = '<html><body><footer>Existing credit & legal</footer></body></html>';
  const result = addCreatorCredit(source);
  assert.equal(result.replace(creatorCreditHtml() + '\n', ''), source);
  assert.equal(addCreatorCredit(result), result);
  assert.ok(result.indexOf('Existing credit') < result.indexOf('data-famtastic-creator-credit'));
});
test('new artifact version preserves old approval evidence and source bytes', () => {
  const root = mkdtempSync(join(tmpdir(), 'fd-credit-test-'));
  const source = join(root, 'source'), output = join(root, 'v2');
  mkdirSync(source);
  const html = '<html><body><footer>Original</footer></body></html>';
  writeFileSync(join(source, 'index.html'), html);
  writeFileSync(join(source, 'approval.json'), '{"historical":true}');
  execFileSync(process.execPath, ['scripts/build-credited-artifact.mjs', source, output]);
  assert.equal(readFileSync(join(source, 'index.html'), 'utf8'), html);
  assert.equal(readFileSync(join(output, 'approval.json'), 'utf8'), '{"historical":true}');
  const receipt = JSON.parse(readFileSync(join(output, 'creator-credit-build-v1.json')));
  assert.equal(receipt.artifacts[0].source_sha256, sha256(html));
  assert.notEqual(receipt.artifacts[0].output_sha256, sha256(html));
  execFileSync(process.execPath, ['scripts/check-creator-credit.mjs', output]);
  assert.notEqual(spawnSync(process.execPath, ['scripts/check-creator-credit.mjs', source]).status, 0);
  assert.notEqual(spawnSync(process.execPath, ['scripts/build-credited-artifact.mjs', source, output]).status, 0);
});
test('proof bundle includes credit before callback byte limit', () => {
  const root = mkdtempSync(join(tmpdir(), 'fd-credit-bundle-'));
  writeFileSync(join(root, 'index.html'), '<html><body>Proof</body></html>');
  execFileSync(process.execPath, ['scripts/bundle-static-proof.mjs', root, join(root, 'bundle.html')]);
  assert.ok(readFileSync(join(root, 'bundle.html'), 'utf8').includes(creatorCreditHtml()));
  writeFileSync(join(root, 'index.html'), '<body>' + 'x'.repeat(499990) + '</body>');
  assert.notEqual(spawnSync(process.execPath, ['scripts/bundle-static-proof.mjs', root, join(root, 'large.html')]).status, 0);
});
test('scoped deploy preserves live copy, backs up exact originals, excludes unpublished HTML', () => {
  const root = mkdtempSync(join(tmpdir(), 'fd-credit-release-'));
  const dist = join(root, 'dist'), live = join(root, 'live'), release = join(root, 'release');
  for (const dir of [dist, live, release, join(dist, 'assets'), join(live, 'assets')]) mkdirSync(dir);
  const index = '<html><body><div id="root"></div><script src="/assets/app.js"></script></body></html>';
  writeFileSync(join(dist, 'index.html'), index);
  writeFileSync(join(dist, 'assets/app.js'), '/* compiled fixture */');
  writeFileSync(join(live, 'index.html'), '<body>old SPA</body>');
  writeFileSync(join(live, 'demo.html'), '<body>LIVE CURRENT COPY<footer>Keep me</footer></body>');
  writeFileSync(join(dist, 'demo.html'), '<body>STALE SOURCE</body>');
  writeFileSync(join(dist, 'new-customer.html'), '<body>Never publish</body>');
  writeFileSync(join(dist, 'creator-credit-build-v1.json'), JSON.stringify({ artifacts: [{path:'index.html',credit:'react-app'}, {path:'demo.html',credit:'static-v1'}, {path:'new-customer.html',credit:'static-v1'}] }));
  execFileSync(process.execPath, ['scripts/deploy-creator-credit-existing.mjs', dist, live, release, 'a'.repeat(40)]);
  const receipt = JSON.parse(readFileSync(join(live, '.creator-credit-release.json')));
  assert.equal(receipt.artifacts.length, 2);
  assert.equal(receipt.excluded[0].path, 'new-customer.html');
  assert.match(readFileSync(join(live, 'demo.html'), 'utf8'), /LIVE CURRENT COPY/);
  assert.doesNotMatch(readFileSync(join(live, 'demo.html'), 'utf8'), /STALE SOURCE/);
  assert.equal(readFileSync(join(release, 'creator-credit-backup/demo.html'), 'utf8'), '<body>LIVE CURRENT COPY<footer>Keep me</footer></body>');
  assert.notEqual(spawnSync(process.execPath, ['scripts/deploy-creator-credit-existing.mjs', dist, live, release, 'a'.repeat(40)]).status, 0);
});
